// 1- Crear dos variables numéricas y utilizar el operador suma para guardar el valor de la suma de ambos números en una 3er variable.
let num1 = 5;
let num2 = 10;
let sum = num1 + num2;
console.log("La suma de num1 y num2 es: " + sum);

// 2- Crear dos variables de tipo String y concatenarlas guardando el resultado en una 3er variable.
let str1 = "Hola, ";
let str2 = "¿Cómo estás?";
let strConcatenado = str1 + str2;
console.log("La concatenación de str1 y str2 es: " + strConcatenado);

// 3- Crear dos variables de tipo String y sumar el largo de cada variable (cantidad de letras del string) guardando el resultado de la suma en una 3er variable (utilizar length).
let str3 = "JavaScript";
let str4 = "HTML";
let totalLetras = str3.length + str4.length;
console.log("La suma del largo de str3 y str4 es: " + totalLetras);

